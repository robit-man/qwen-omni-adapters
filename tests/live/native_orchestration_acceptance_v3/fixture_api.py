"""Read frozen captured inputs; no model, desktop or service operations."""

import copy
import hashlib
import json
from pathlib import Path

PANEL = Path(__file__).resolve().parent


def _json(path):
    content = path.read_bytes()
    if len(content) > 2 * 1024 * 1024:
        raise ValueError("Frozen source exceeds bound")
    return json.loads(content)


def load_frozen_panel():
    manifest = _json(PANEL / "manifest.json")
    for name, expected in manifest["files"].items():
        path = PANEL / name
        if not path.resolve().is_relative_to(PANEL) or path.is_symlink():
            raise ValueError("Invalid frozen source path")
        if hashlib.sha256(path.read_bytes()).hexdigest() != expected:
            raise ValueError("Frozen diagnostic changed")
    return _json(PANEL / "acceptance.json")


def model_inputs(source_id):
    """Compiler-side source material; never send this private envelope to a model.

    Oracles and reconstructed golden anchors are deliberately absent. Candidate
    proposals must be generated by the actual model, not filled from host cases.
    """
    source = load_frozen_panel()["sources"][source_id]
    bind = _json(PANEL / source["bind_file"])
    expand = _json(PANEL / source["expand_file"])
    return {
        "compact": copy.deepcopy(bind["arguments"][0]),
        "binding": copy.deepcopy(bind["arguments"][1]),
        "packet": copy.deepcopy(expand["arguments"][1]),
        "proposal_request": _json(PANEL / source["request_files"]["proposal"]["file"]),
        "action_request": _json(PANEL / source["request_files"]["action"]["file"]),
    }


def host_inputs(case_id):
    """Counterfactual guard probe only; its golden anchor is not a model input."""
    spec = load_frozen_panel()
    case = next(c for c in spec["host_cases"] if c["case_id"] == case_id)
    source = spec["sources"][case["source_id"]]
    decision_source = spec["sources"][case["decision_source_id"]]
    bind = _json(PANEL / source["bind_file"])
    expand = _json(PANEL / source["expand_file"])
    decision_expand = _json(PANEL / decision_source["expand_file"])
    proposal = copy.deepcopy(bind["arguments"][2])
    if case["proposal_anchor"] == "source_counterfactual":
        proposal["immediate_action"] = copy.deepcopy(source["counterfactual_anchor"])
    decision = copy.deepcopy(decision_expand["arguments"][0])
    if "action_replace" in case:
        objective = decision["action"]["objective"]
        decision["action"] = {**copy.deepcopy(case["action_replace"]), "objective": objective}
    decision["action"].update(case.get("action_patch", {}))
    return {
        "compact": copy.deepcopy(bind["arguments"][0]),
        "binding": copy.deepcopy(bind["arguments"][1]),
        "packet": copy.deepcopy(expand["arguments"][1]),
        "proposal": proposal,
        "decision": decision,
        "atomic_anchor": True,
    }
